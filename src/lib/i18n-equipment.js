// Every block below except `en` was produced by an LLM, not a native
// speaker. This is a deliberate exception to CLAUDE.md's "don't ship
// machine-translated copy" rule, taken by Kegan on 2026-07-30 on the
// reasoning that for 37 short UI strings, a reviewed-later translation
// serves a Japanese or Turkish lifter better than an English fallback.
//
// It is NOT a change to the rule. Do not treat this file as precedent
// for machine-translating prose, onboarding, marketing, or anything
// longer than a label. When a native speaker reviews a language, delete
// that language from REVIEW_PENDING below.
//
// Highest-risk strings for a reviewer to check first, because they carry
// meaning a literal translation loses:
//   • gymEquip.byGym / gymEquip.confirmed — these are TRUST BADGES.
//     "Listed by the gym" = the gym's own owner added it (authoritative).
//     "Confirmed" = the owner vouched for a member's submission. If a
//     language collapses these two into the same word, the distinction
//     users rely on disappears.
//   • gymEquip.added / emptyMine / emptyOther — English "the floor"
//     means the gym's equipment area. Rendered as "the gym" elsewhere,
//     since "floor" is idiomatic and translates badly.
//   • implement.clear — the VERB (clear a selection), not the adjective.
//   • gymEquip.save is "Add" while implement.save is "Save" — different
//     buttons, deliberately different words.
//
// Translator notes that apply to every language:
//
//  • "implement" in the code means the specific piece of equipment a
//    lifter is using. User-facing copy never says "implement"; it says
//    "equipment".
//
//  • BRAND AND MODEL NAMES ARE NEVER TRANSLATED. "Hammer Strength",
//    "Bowflex SelectTech 552", "Cybex Eagle" are proper nouns generated
//    from src/lib/equipmentCatalog.js, not from this file.
//
//  • `implement.atGymNamed` takes a {gym} placeholder holding the gym's
//    own name. Keep the placeholder and put it where the target language
//    wants it — never split it into a preposition plus a name.
//
//  • `implement.customPlaceholder` is example text in an input. The
//    machine name inside it ("Atlantis leg press") should be localised
//    the way a lifter in that language would actually say it.

