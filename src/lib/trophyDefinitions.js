export const TROPHY_BY_ID = Object.fromEntries(TROPHIES.map(t => [t.id, t]));

// ── League season trophies ────────────────────────────────────────────────
//
// These cannot live in TROPHIES, because a new one is minted every 28 days
// and a static catalog would need editing on every roll. They are resolved
// from the id instead: `league_s{n}_{tier}` and `league_s{n}_champion`, both
// written by award_league_season_internal (migration 312).
//
// `TROPHIES.length` is the denominator for the "12 / 40 earned" counter on
// the profile, so season trophies are deliberately NOT added to it — an
// unreachable denominator that grows forever would make the collection look
// permanently unfinished.

const SEASON_TROPHY_RE = /^league_s(\d+)_(bronze|silver|gold|platinum|diamond|legend|champion)$/;

// TROPHY_TIERS has no `diamond` step, so diamond borrows platinum's ramp and
// both legend and champion take `legendary`.
const SEASON_TIER_MAP = {
  bronze: 'bronze', silver: 'silver', gold: 'gold',
  platinum: 'platinum', diamond: 'platinum',
  legend: 'legendary', champion: 'legendary',
};

const SEASON_EMOJI = {
  bronze: '🥉', silver: '🥈', gold: '🥇',
  platinum: '💠', diamond: '💎', legend: '👑', champion: '👑',
};

/** Parsed season trophy, or null if `id` isn't one. */
export function parseSeasonTrophy(id) {
  const m = SEASON_TROPHY_RE.exec(id || '');
  if (!m) return null;
  const season = Number(m[1]);
  const kind = m[2];
  const isChampion = kind === 'champion';
  const label = kind.charAt(0).toUpperCase() + kind.slice(1);
  return {
    id,
    season,
    kind,
    isChampion,
    category: 'league',
    tier: SEASON_TIER_MAP[kind] || 'bronze',
    emoji: SEASON_EMOJI[kind] || '🎖️',
    name: isChampion ? `Champion, S${season}` : `Season ${season} ${label}`,
    description: isChampion
      ? `Won season ${season} outright. Minted once — nobody else can earn this one.`
      : `Reached ${label} in season ${season}.`,
  };
}

// ── Infinite ladder tails ─────────────────────────────────────────
//
// Past the last named rung, ids are generated rather than enumerated:
// `sessions_x1` is 200 workouts, `sessions_x2` is 300, and so on. Same
// trick as the league season trophies above, for the same reason — the
// alternative is a catalog that has to be edited every time somebody
// out-trains it.
//
// Tail rung k requires `tailBase + k * tailStep` and displays as the
// top rung's name in Roman numerals: k=1 → "Centurion II".
//
// Like season trophies, these are NOT in TROPHIES — see the header.

const TAIL_RE = /^([a-z]+)_x(\d+)$/;

// A cap on generated rungs, mirrored in migration 323. Nobody is
// legitimately 50 tail-rungs deep, so a number past this means corrupt
// data rather than a very dedicated user, and it stops one bad
// `total_volume_lbs` from minting thousands of rows.
export const TAIL_CAP = 50;

const ROMAN = [
  [1000, 'M'], [900, 'CM'], [500, 'D'], [400, 'CD'], [100, 'C'], [90, 'XC'],
  [50, 'L'], [40, 'XL'], [10, 'X'], [9, 'IX'], [5, 'V'], [4, 'IV'], [1, 'I'],
];

/** 4 → "IV". Used for tail rung numerals. */
export function toRoman(n) {
  let out = '';
  let rest = Math.max(0, Math.floor(n));
  for (const [value, numeral] of ROMAN) {
    while (rest >= value) { out += numeral; rest -= value; }
  }
  return out;
}

/** Parsed tail trophy, or null if `id` isn't one. */
export function parseLadderTail(id) {
  const m = TAIL_RE.exec(id || '');
  if (!m) return null;
  const ladderId = m[1];
  const k = Number(m[2]);
  const ladder = LADDERS[ladderId];
  // A tail on a ladder that has none is not a trophy — it's a typo or a
  // forged id. Resolve it to null so it renders as nothing rather than
  // as a plausible-looking badge.
  if (!ladder || ladder.tailBase == null || k < 1 || k > TAIL_CAP) return null;

  const threshold = ladder.tailBase + k * ladder.tailStep;
  // Tails sit above the top named rung, so they take the top tier of
  // the ramp. There is nowhere further to escalate.
  return {
    id,
    ladder: ladderId,
    category: ladder.category,
    tier: 'legendary',
    emoji: '♾️',
    threshold,
    isTail: true,
    name: `${ladder.tailName} ${toRoman(k + 1)}`,
    description: `${threshold.toLocaleString()} ${ladder.unit}`.trim(),
  };
}

export function getTrophy(id) {
  return TROPHY_BY_ID[id] || parseSeasonTrophy(id) || parseLadderTail(id) || null;
}

// ── "What's next" ─────────────────────────────────────────────────
//
// The whole point of the ladder structure: given where someone is on a
// ladder, hand back the ONE rung they're working toward. The page shows
// this rather than the full wall, so finishing a rung immediately
// replaces it with the next one instead of leaving a gap.
//
// Returns null only for a ladder that has genuinely ended — the
// deliberate dead ends (see LADDERS). Everything else always answers.
const RUNGS_BY_LADDER = TROPHIES.reduce((acc, t) => {
  if (!t.ladder) return acc;
  (acc[t.ladder] ||= []).push(t);
  return acc;
}, {});
Object.values(RUNGS_BY_LADDER).forEach(list => list.sort((a, b) => a.threshold - b.threshold));

/** Every named rung on a ladder, lowest threshold first. */
export function rungsFor(ladderId) {
  return RUNGS_BY_LADDER[ladderId] || [];
}

/**
 * The next rung on `ladderId` for someone whose signal reads `value`.
 * Falls through the named rungs, then into the generated tail.
 */
export function nextRung(ladderId, value = 0) {
  const ladder = LADDERS[ladderId];
  if (!ladder) return null;

  const named = rungsFor(ladderId).find(r => value < r.threshold);
  if (named) return named;

  // Past every named rung — walk into the tail.
  if (ladder.tailBase == null) return null;
  const k = Math.floor((value - ladder.tailBase) / ladder.tailStep) + 1;
  return parseLadderTail(`${ladderId}_x${Math.min(Math.max(k, 1), TAIL_CAP)}`);
}

/**
 * Progress toward `trophy` given the caller's signal value, as
 * { value, target, pct, done }. `pct` is clamped to 0–100.
 */
export function rungProgress(trophy, value = 0) {
  const target = trophy?.threshold || 0;
  const done = target > 0 && value >= target;
  const pct = target > 0 ? Math.min(100, Math.max(0, (value / target) * 100)) : 0;
  return { value, target, pct, done };
}
