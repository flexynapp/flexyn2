// src/lib/trophyDefinitions.js
//
// Earned-trophy catalog. These are AUTO-AWARDED milestones — distinct
// from the decorative emoji picker on the profile (that one lets a
// user choose any 5 emojis for display; this one tracks achievements
// they've actually unlocked).
//
// Criteria are checked SERVER-SIDE in grant_eligible_trophies()
// (migrations 167 + 323) so a client can't fake having earned one.
// The catalog here mirrors the server's list — when you change one,
// change the other.
//
// ── LADDERS: why every trophy belongs to one ──────────────────────
//
// A flat list of badges has an end, and the day a user collects the
// last one the feature is over for them. Every trophy here is a RUNG
// on a named ladder instead, and three mechanics guarantee there is
// always a next thing:
//
//   1. Rungs are ordered. Clearing "Consistent" (10 workouts) reveals
//      "Committed" (50) as the live target — the page shows the next
//      rung, not the whole wall.
//   2. Most ladders have an INFINITE TAIL. Past the last named rung,
//      ids are generated by formula — `sessions_x1` is 200 workouts,
//      `sessions_x2` is 300 — and resolved by parseLadderTail() the
//      same way parseSeasonTrophy() resolves league trophies. The
//      catalog stays finite; the ladder does not.
//   3. Some ladders don't exist until you're in the feature at all
//      (crew wars, gauntlet, prestige), so the board grows sideways
//      as well as upward.
//
// A few ladders deliberately DEAD-END, and that is a design decision
// rather than an oversight — see `tailBase: null` and the note on
// each. Anything that would reward training longer, further or more
// often without limit is a ladder we should not build.
//
// TAIL IDS ARE NOT IN `TROPHIES`, for the same reason league season
// trophies aren't: TROPHIES.length is the "12 / 40 earned" denominator
// on the profile, and a denominator that grows forever would make
// every collection look permanently unfinished.

