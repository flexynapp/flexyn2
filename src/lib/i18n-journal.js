// My Journal + Readiness-sheet i18n.
//
// ⚠️  LABELS ARE MACHINE TRANSLATED — PENDING NATIVE REVIEW  ⚠️
//
// Every block below except `en` was produced by an LLM, not a native
// speaker. This is the SECOND deliberate exception to CLAUDE.md's "don't
// ship machine-translated copy" rule, taken by Kegan on 2026-08-09 — and
// it is deliberately narrower than the first (i18n-equipment.js).
//
// THE SPLIT, which is the whole point of this file:
//
//   • SHORT UI LABELS are translated. "Saved", "Log", "Try again",
//     "not logged", "Last night's sleep". A reviewed-later label serves a
//     Japanese or Turkish lifter better than an English fallback.
//   • PROSE IS NOT. Every full sentence stays English and is listed in
//     ENGLISH_ONLY below. Machine-written sentences on a prominent
//     surface are exactly what the rule exists to prevent, and this
//     screen has fourteen of them.
//
// So a native reviewer has two jobs, not one: check the labels here, and
// TRANSLATE the ENGLISH_ONLY list, which nothing has attempted.
//
// Highest-risk strings for a reviewer, because a literal translation
// loses the meaning:
//
//   • journal.held / journal.notSaved / journal.saved are the SAVE STATE
//     and they are three different promises. "Saved" = the server has
//     it. "Held offline" = it failed and we are still retrying. "Not
//     saved — tap to retry" = we have STOPPED retrying and the user must
//     act. If a language blurs these, someone will close the app
//     believing their writing is safe when it is sitting in localStorage.
//   • journal.prov.written vs journal.prov.edited — "Written 2 days
//     later" means the entry never existed on its own day; "Edited 3
//     days later" means it did and was amended. Different facts.
//   • readiness.notLogged is a STATUS, not an instruction — it labels a
//     signal the user has not provided. Lowercase in English on purpose.
//   • journal.feltLabel ("You felt") is a sentence FRAGMENT: the mood
//     word from mood.label.N is appended to it, so it must read
//     naturally with a following adjective, and languages that put the
//     adjective first should reorder the whole phrase rather than leave
//     a dangling verb.
//   • readiness.saveClose is drawn on Penpot board 02 as "Save & close".
//     It both commits pending input and dismisses; keep both verbs.
//   • journal.fromToday / fromThatDay are UPPERCASE section labels in
//     English. Languages without case (ja, ko, zh, ar, hi) render them
//     normally — that is correct, not a missed conversion.
//
// PLACEHOLDERS: {n}, {d} and {name} are substituted at the call site.
// Keep them exactly; move them where the target language wants them.
// Never split a placeholder across words.
//
// PLURALS: the app has no plural engine. `journal.prov.day` (exactly 1)
// and `journal.prov.days` ({n} > 1) are the only pair, chosen at the call
// site. Languages with richer plural rules than two forms have to pick
// the form that reads least badly for {n} > 1 — flag it for the
// reviewer rather than inventing a rule this codebase cannot honour.

